// Each has its own first questions (answered by a press, or by writing: the box under them is always open), its own steps for «محمد باقر»,
// and the rules of the talk he follows in every path: short by default, longer when the person asks, and sharp at understanding edits.
// The path travels in the person's messages as a mark [مسار:id] (see lib/content/marks.ts), so the last one wins when they switch.

export const CONTENT_PATH_IDS = ["carousel", "motion-carousel", "motion-graphics", "reel-graphics"] as const;
export type ContentPathId = (typeof CONTENT_PATH_IDS)[number];
export const isContentPath = (v: unknown): v is ContentPathId => typeof v === "string" && (CONTENT_PATH_IDS as readonly string[]).includes(v);

/** A first question of a path: answers are buttons (several may be pressed when `multi`); the person may always write instead. */
export interface PathQuestion {
  label: string;
  kind: "choice";
  options: string[];
  multi: boolean;
}

export interface ContentPath {
  id: ContentPathId;
  name: string;
  ic: string;
  color: string;
  /** one line on the start card */
  short: string;
  /** what «محمد باقر» says first (written here, so opening a path costs nothing) */
  opening: string;
  /** the first batch: the few decisions that change everything else */
  first: PathQuestion[];
  /** the steps, in order (the guide of the path) */
  steps: string[];
  /** what «محمد باقر» is told about this path, every turn */
  flow: string;
}

const choice = (label: string, options: string[], multi = false): PathQuestion => ({ label, kind: "choice", options, multi });

