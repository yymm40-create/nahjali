export const SFX_LIBRARY: SfxItem[] = Object.entries(ROWS).flatMap(([cat, rows]) =>
  rows.map(([id, name, prompt, seconds, loop]) => ({ id: `${cat}-${id}`, cat, name, prompt, seconds, ...(loop ? { loop } : {}) })),
);

export const sfxById = (id: string) => SFX_LIBRARY.find((s) => s.id === id);
export const sfxPath = (id: string) => `${SFX_LIBRARY_DIR}/${id}.mp3`;
/** What making the whole list (or a part of it) costs the site at ElevenLabs, USD. */
export const sfxCostUsd = (items: Pick<SfxItem, "seconds">[]) => items.reduce((n, s) => n + s.seconds, 0) * SFX_USD_PER_SECOND;
