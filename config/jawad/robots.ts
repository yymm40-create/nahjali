/** Which robot lives on this page of JAWAD AI (null when none does). */
export function robotFor(path: string): RobotIntro | null {
  const p = path.replace(/\/+$/, "") || "/";
  if (p === "/jawad-ai") return ROBOTS.salman;
  const m = /^\/jawad-ai\/([^/]+)/.exec(p);
  const seg = m?.[1] ?? "";
  const byPage: Record<string, string> = {
    images: "jawad",
    video: "jawad",
    audio: "jawad",
    film: "sajjad",
    editor: "haidara",
    student: "sadiq",
    islamic: "islamic",
    games: "qanbar",
    content: "baqir",
    designer: "kazim",
    photo: "zahraa",
    kharq: "kharq",
    booklet: "booklet",
  };
  return byPage[seg] ? ROBOTS[byPage[seg]] : null;
}
