const plural = (n: number, forms: Partial<Record<Intl.LDMLPluralRule, string>> & { other: string }) => {
  const rule = new Intl.PluralRules("ar").select(n);
  return (forms[rule] ?? forms.other).replace("{n}", String(n));
};

